"""Revision pages generated from the chapters (called by gen_book.py).

    books/appendix/cheatsheets.qmd    per chapter: the Summary's template callout + the Pattern map
    books/appendix/question_bank.qmd  per chapter: the Interview questions, with a quiz mode
    books/appendix/glossary.qmd       from glossary.yml, alphabetical, each term linked to its section

Copied text drops `{#...}` labels, so no id is defined twice; cross-references (@sec-...) still
point to the chapter. Chapters are read in outline order, includes expanded.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from qmdlib import BOOKS, ROOT, expand

H1 = re.compile(r"^# (.+?)\s*\{#(sec-[\w-]+)[^}]*\}", re.M)
LABEL_ATTR = re.compile(r"\s*\{#[\w-]+\}")
ANY_LABEL = re.compile(r"\{#(sec-[\w-]+)")
GENERATED = "<!-- Generated by scripts/gen_book.py (gen_revise.py) from the chapters. Do not edit. -->"


def section(text: str, title: str) -> str:
    """Body of the level-2 section whose heading starts with `title` (up to the next level-1/2 heading)."""
    lines, out, on, code = text.splitlines(), [], False, False
    for line in lines:
        if line.startswith("```"):
            code = not code
        if not code and re.match(r"^#{1,2} ", line):
            if on:
                break
            on = line.startswith(f"## {title}")
            continue
        if on:
            out.append(line)
    return "\n".join(out).strip()


def divs(text: str, cls: str) -> list[str]:
    """Every fenced div (::: {.cls ...}) in text, fences included; nested divs are kept inside."""
    out, lines, i = [], text.splitlines(), 0
    while i < len(lines):
        if re.match(rf"^(:{{3,}})\s*\{{\.{cls}\b", lines[i]):
            depth, j = 0, i
            while j < len(lines):
                if re.match(r"^:{3,}\s*\{", lines[j]) or re.match(r"^:{3,}\s*\w", lines[j]):
                    depth += 1
                elif re.match(r"^:{3,}\s*$", lines[j]):
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            out.append("\n".join(lines[i:j + 1]))
            i = j + 1
        else:
            i += 1
    return out


def clean(md: str) -> str:
    return LABEL_ATTR.sub("", md)


def chapters_in_order(volumes: list[dict]) -> list[tuple[dict, Path]]:
    return [(c, BOOKS / c["file"]) for v in volumes for p in v["parts"] for c in p["chapters"] if c["file"]]


def write_cheatsheets(volumes: list[dict]) -> int:
    out = ["# Cheat Sheets {#sec-cheatsheets}", "", GENERATED, "",
           "One screen per chapter: the templates to remember and the map from what a statement says "
           "to the pattern that solves it. Use it the night before an interview or a contest; follow a "
           "link when a line no longer makes sense.", ""]
    n = 0
    for c, path in chapters_in_order(volumes):
        text = expand(path)[0]
        h = H1.search(text)
        summary, pmap = section(text, "Summary"), section(text, "Pattern map")
        templates = divs(summary, "callout-important")
        if not (templates or pmap):
            continue
        n += 1
        title, label = (h[1], h[2]) if h else (c["title"], None)
        out += [f"## {c['num']} · {title} {{.unnumbered .cs-chapter}}", ""]
        if label:
            out += [f"[Chapter: @{label}]{{.cs-link}}", ""]
        out += [clean(t) + "\n" for t in templates]
        if pmap:
            out += ["::: {.cs-map}", clean(pmap), ":::", ""]
    (BOOKS / "appendix" / "cheatsheets.qmd").write_text("\n".join(out) + "\n", encoding="utf-8")
    return n


QUESTION = re.compile(r"^\*\*(\d+)\.\s")


def write_question_bank(volumes: list[dict]) -> int:
    out = ["# Question Bank {#sec-question-bank}", "", GENERATED, "",
           "Every interview question in the book, by chapter, with its answer folded away. Say your answer "
           "out loud before you open the fold. **Quiz mode** asks one question at a time, limited to one "
           "chapter if you like. Mark each answer *Got it* or *Again*: questions you miss come back first "
           "next time (saved in this browser).", "",
           '```{=html}',
           '<div class="quiz-bar"><select class="quiz-scope" aria-label="Chapters to quiz">'
           '<option value="">All chapters</option></select>'
           '<button class="quiz-start" type="button">Start quiz mode</button>'
           '<button class="quiz-got" type="button" hidden>Got it</button>'
           '<button class="quiz-again" type="button" hidden>Again</button>'
           '<button class="quiz-stop" type="button" hidden>Show all</button>'
           '<span class="quiz-status" aria-live="polite"></span></div>',
           '```', ""]
    total = 0
    for c, path in chapters_in_order(volumes):
        text = expand(path)[0]
        body = section(text, "Interview questions")
        if not body:
            continue
        h = H1.search(text)
        title, label = (h[1], h[2]) if h else (c["title"], None)
        out += [f"## {c['num']} · {title} {{.unnumbered .qb-chapter}}", ""]
        if label:
            out += [f"[Chapter: @{label}]{{.cs-link}}", ""]
        items, cur = [], []
        for line in body.splitlines():
            if QUESTION.match(line) and cur:
                items.append(cur)
                cur = []
            cur.append(line)
        if cur:
            items.append(cur)
        for it in items:
            if not QUESTION.match(it[0]):
                out += [clean("\n".join(it)), ""]      # any lead-in text before the first question
                continue
            total += 1
            out += [f'::: {{.qb-item data-chapter="{c["num"]}"}}', clean("\n".join(it).strip()), ":::", ""]
    (BOOKS / "appendix" / "question_bank.qmd").write_text("\n".join(out) + "\n", encoding="utf-8")
    return total


def known_labels() -> set[str]:
    labels = set()
    for f in BOOKS.rglob("*.qmd"):
        if "_freeze" in f.parts or "_book" in f.parts:
            continue
        labels.update(ANY_LABEL.findall(f.read_text(encoding="utf-8")))
    return labels


def write_glossary() -> tuple[int, list[str]]:
    src = ROOT / "glossary.yml"
    entries = yaml.safe_load(src.read_text(encoding="utf-8")) if src.exists() else []
    labels, missing = known_labels(), []
    out = ["# Glossary {#sec-glossary}", "", "<!-- Generated by scripts/gen_book.py from glossary.yml. "
           "Do not edit; add terms to glossary.yml. -->", "",
           "The words this book uses with a fixed meaning. Each entry links to the section that introduces it.", ""]
    letter = None
    for e in sorted(entries, key=lambda e: e["term"].lower()):
        first = e["term"][0].upper()
        if first != letter:
            letter = first
            out += [f"## {letter} {{.unnumbered}}", ""]
        see = e.get("see")
        ref = ""
        if see:
            if see in labels:
                ref = f" See @{see}."
            else:
                missing.append(f"{e['term']}: {see}")
        out += [f"{e['term']}", f":   {e['def'].strip()}{ref}", ""]
    (BOOKS / "appendix" / "glossary.qmd").write_text("\n".join(out) + "\n", encoding="utf-8")
    return len(entries), missing
