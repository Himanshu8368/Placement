"""Create a registry problem: books/problems/<key>/{problem.qmd, solution.qmd}.

    python scripts/new_problem.py LC 70 "Climbing Stairs" --difficulty Easy
    python scripts/new_problem.py CF 1155D "Beautiful Array" --rating 1900
    python scripts/new_problem.py AC dp_a "Frog 1"
    python scripts/new_problem.py CSES 1633 "Dice Combinations"

Then, in the chapter where the problem is solved (its home):
    {{< include ../problems/<key>/problem.qmd >}}
and anywhere else it is reused, the generated card (or the code):
    {{< include ../problems/<key>/card.qmd >}}       short pointer to the home write-up
    {{< include ../problems/<key>/solution.qmd >}}   the same tested code, run again
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from qmdlib import PROBLEMS, ROOT  # noqa: E402


def slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def url_for(judge: str, pid: str, name: str, lc_slug: str | None) -> str:
    if judge == "LC":
        return f"https://leetcode.com/problems/{lc_slug or slugify(name)}/"
    if judge == "CF":
        m = re.fullmatch(r"(\d+)([A-Za-z]\d?)", pid)
        if not m:
            raise SystemExit("CF id looks like 1155D")
        return f"https://codeforces.com/problemset/problem/{m[1]}/{m[2].upper()}"
    if judge == "AC":
        return f"https://atcoder.jp/contests/{pid.split('_')[0]}/tasks/{pid}"
    if judge == "CSES":
        return f"https://cses.fi/problemset/task/{pid}"
    raise SystemExit("judge must be LC, CF, AC or CSES")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("judge", choices=["LC", "CF", "AC", "CSES"])
    ap.add_argument("id")
    ap.add_argument("name")
    ap.add_argument("--difficulty", choices=["Easy", "Medium", "Hard"])
    ap.add_argument("--rating", type=int)
    ap.add_argument("--lc-slug", help="LeetCode slug when it differs from the slugified name")
    a = ap.parse_args()

    pid = a.id.zfill(4) if a.judge == "LC" else a.id.lower()
    key = f"{a.judge.lower()}-{pid}-{slugify(a.name)}"
    folder = PROBLEMS / key
    if folder.exists():
        raise SystemExit(f"{folder} already exists")
    attrs = ".solved"
    if a.judge == "LC":
        attrs += f' difficulty="{a.difficulty or "Medium"}"'
    if a.judge == "CF":
        attrs += f' rating="{a.rating or 0}"'
    link = f"[{a.judge} {a.id} · {a.name}]({url_for(a.judge, a.id, a.name, a.lc_slug)}){{{attrs}}}"
    fn = re.sub(r"[^a-z0-9]+", "_", a.name.lower()).strip("_")

    problem = f"""### Problem: {a.name} {{#sec-p-{key}}}

::: {{.p-statement}}
Restatement with constraints.

Source: {link}
:::

::: {{.p-intuition}}
The one observation that makes the problem easy. (This paragraph is also the problem's card text.)
:::

::: {{.p-approach}}
1. **Brute force.** … and its cost.
2. **Refined.** … and the invariant.
:::

The buttons are in order. Each one keeps the previous solution and changes only what that form changes.

::: {{.panel-tabset .solution-forms}}

#### Brute force

::: {{.form-next}}
What this form does and what it costs.
:::

::: {{.panel-tabset group="lang"}}
##### Python
```{{python}}
def {fn}_brute(*args):
    ...
```
##### C++
```cpp
// brute force
```
:::

#### Refined

::: {{.form-next}}
What changes from the brute force, and why it is faster.
:::

::: {{.panel-tabset group="lang"}}
##### Python
{{{{< include ../problems/{key}/solution.qmd >}}}}
##### C++
```cpp
// refined solution
```
:::
:::

::: {{.p-complexity}}
**Brute force**: … **Refined**: …
:::

::: {{.p-edge}}
- …
:::

::: {{.practice}}
- …
:::
"""
    solution = f"""```{{python}}
def {fn}(*args):
    ...


# Stress test against the brute force (defined in the first form), then the official samples.
for _ in range(300):
    pass
```
"""
    folder.mkdir(parents=True)
    (folder / "problem.qmd").write_text(problem, encoding="utf-8")
    (folder / "solution.qmd").write_text(solution, encoding="utf-8")
    print(f"created {folder.relative_to(ROOT)}\n  home chapter:  {{{{< include ../problems/{key}/problem.qmd >}}}}"
          f"\n  elsewhere:     {{{{< include ../problems/{key}/card.qmd >}}}}  (card is generated by gen_book.py)")


if __name__ == "__main__":
    main()
